// --- the model's own schedule maths -------------------------------------------------------

it('finds the next occurrence after an instant, in UTC, honouring the start and end dates', function () {
    $slot = new RecurringSlot([
        'weekday' => 2, 'start_time' => '17:00:00', 'timezone' => 'Asia/Karachi',
        'starts_on' => '2026-09-14', 'ends_on' => '2026-09-22',
    ]);

    // Tuesday 17:00 PKT = 12:00Z.
    expect($slot->nextOccurrenceAfter(CarbonImmutable::parse('2026-09-14 06:00:00', 'UTC'))->toIso8601String())->toBe('2026-09-15T12:00:00+00:00')
        // Strictly after: at the occurrence itself, the next week's.
        ->and($slot->nextOccurrenceAfter(CarbonImmutable::parse('2026-09-15 12:00:00', 'UTC'))->toIso8601String())->toBe('2026-09-22T12:00:00+00:00')
        // Past the end date there is none.
        ->and($slot->nextOccurrenceAfter(CarbonImmutable::parse('2026-09-22 12:00:00', 'UTC')))->toBeNull()
        ->and($slot->scheduleLabel())->toBe('Tuesday 17:00 (Asia/Karachi)');

    $starts = new RecurringSlot(['weekday' => 2, 'start_time' => '17:00:00', 'timezone' => 'UTC', 'starts_on' => '2026-10-06']);
    expect($starts->nextOccurrenceAfter(CarbonImmutable::parse('2026-09-14 06:00:00', 'UTC'))->toDateString())->toBe('2026-10-06');
});

it('keeps the next occurrence on wall-clock time across a daylight-saving change', function () {
    $slot = new RecurringSlot(['weekday' => 0, 'start_time' => '17:00:00', 'timezone' => 'Europe/London', 'starts_on' => '2026-10-01']);

    // Sunday 18 Oct is still BST (17:00 = 16:00Z); Sunday 25 Oct is GMT (17:00 = 17:00Z).
    expect($slot->nextOccurrenceAfter(CarbonImmutable::parse('2026-10-14 00:00:00', 'UTC'))->toIso8601String())->toBe('2026-10-18T16:00:00+00:00')
        ->and($slot->nextOccurrenceAfter(CarbonImmutable::parse('2026-10-18 16:00:00', 'UTC'))->toIso8601String())->toBe('2026-10-25T17:00:00+00:00');
});

