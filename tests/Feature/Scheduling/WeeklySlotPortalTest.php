it('shows the parent what ending releases and what stays, then ends the slot at once', function () {
    Mail::fake();
    ['slot' => $slot, 'parent' => $parent, 'learner' => $learner, 'setup' => $setup] = wpSlotWithLessons();

    $lessons = Lesson::query()->where('recurring_slot_id', $slot->id)->orderBy('starts_at')->get();
    $paid = $lessons->first();
    LessonStateMachine::transition($paid, LessonStatus::Confirmed);
    $reserved = $lessons->count() - 1;

    test()->actingAs($parent)->get(route('weekly-slots.end.show', $slot))
        ->assertOk()
        ->assertInertia(fn ($page) => $page->component('weekly-slots/End')
            ->where('reserved_count', $reserved)
            ->has('confirmed', 1)
            ->where('confirmed.0.id', $paid->id)
            ->where('weekly_slot.ended', false));

    test()->actingAs($parent)->post(route('weekly-slots.end', $slot))
        ->assertRedirect(route('learners.show', $learner));

    expect($slot->fresh()->status)->toBe(RecurringSlotStatus::Ended)
        ->and($paid->fresh()->status)->toBe(LessonStatus::Confirmed)
        ->and(Lesson::query()->where('recurring_slot_id', $slot->id)->where('status', LessonStatus::CancelledByParent)->count())->toBe($reserved)
        ->and(Lesson::query()->where('recurring_slot_id', $slot->id)->where('cancel_reason', LessonCancelReason::SlotEnded->value)->count())->toBe($reserved);

    // One email per party, none per released lesson.
    Mail::assertQueued(RecurringSlotEndedMail::class, 2);
    Mail::assertQueued(RecurringSlotEndedMail::class, fn ($m) => $m->hasTo($setup['tutor']->user->email) && $m->paidLessonsRemaining === 1 && $m->releasedLessons === $reserved);
    Mail::assertNotQueued(LessonSkippedMail::class);
});

