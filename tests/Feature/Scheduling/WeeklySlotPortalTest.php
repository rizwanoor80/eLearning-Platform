/**
 * A bookable tutor who teaches one subject and is available on one weekday.
 *
 * @return array{tutor: TutorProfile, curriculum_id: int, subject_id: int}
 */
function wpTutor(string $timezone = 'UTC', string $from = '09:00:00', string $to = '12:00:00', int $weekday = 2): array
{
    $curriculum = Curriculum::query()->firstOrCreate(['code' => CurriculumCode::Gcse], ['name' => CurriculumCode::Gcse->value, 'sort' => 0]);
    $subject = Subject::factory()->create();
    $tutor = TutorProfile::factory()->approved()->create(['hourly_rate' => 10000]);

    TutorSubject::factory()->create([
        'tutor_profile_id' => $tutor->id,
        'curriculum_id' => $curriculum->id,
        'subject_id' => $subject->id,
        'level_tier' => LevelTier::LowerSecondary,
    ]);

    PriceBand::query()->firstOrCreate(
        ['curriculum_id' => $curriculum->id, 'level_tier' => LevelTier::LowerSecondary, 'effective_from' => '2000-01-01'],
        ['min_rate' => 5000, 'max_rate' => 20000],
    );

    AvailabilityRule::factory()->create([
        'tutor_profile_id' => $tutor->id, 'weekday' => $weekday, 'start_time' => $from, 'end_time' => $to, 'timezone' => $timezone,
    ]);

    return ['tutor' => $tutor->fresh(), 'curriculum_id' => $curriculum->id, 'subject_id' => $subject->id];
}

/**
 * A parent with one learner, optionally a saved card and a completed trial with the tutor.
 *
 * @return array{parent: User, learner: Learner}
 */
function wpParent(TutorProfile $tutor, bool $trial = true, bool $card = true, string $timezone = 'UTC'): array
{
    $parent = User::factory()->create(['timezone' => $timezone]);
    $learner = Learner::factory()->create(['account_user_id' => $parent->id, 'curriculum_id' => gcseCurriculumId()]);

    if ($card) {
        PaymentMethod::factory()->create(['account_user_id' => $parent->id]);
    }

    if ($trial) {
        static $offset = 0;
        $at = now()->subDays(3)->subHours(++$offset);

        Lesson::factory()->trial()->withStatus(LessonStatus::Completed)->create([
            'tutor_profile_id' => $tutor->id,
            'learner_id' => $learner->id,
            'starts_at' => $at,
            'ends_at' => $at->addHour(),
        ]);
    }

    return ['parent' => $parent, 'learner' => $learner];
}

/**
 * @param  array<string, mixed>  $extra
 * @return array<string, mixed>
 */
function wpForm(array $setup, Learner $learner, array $extra = []): array
{
    return array_merge([
        'learner_id' => $learner->id,
        'tutor_id' => $setup['tutor']->id,
        'curriculum_id' => $setup['curriculum_id'],
        'subject_id' => $setup['subject_id'],
        'weekday' => 2,
        'start_time' => '10:00',
        'starts_on' => '2026-09-22',
    ], $extra);
}

/**
 * A live slot on the setup's tutor with reserved lessons generated by the real job.
 *
 * @return array{slot: RecurringSlot, parent: User, learner: Learner, setup: array<string, mixed>}
 */
function wpSlotWithLessons(): array
{
    $setup = wpTutor();
    ['parent' => $parent, 'learner' => $learner] = wpParent($setup['tutor']);

    $slot = RecurringSlot::factory()->create([
        'learner_id' => $learner->id,
        'tutor_profile_id' => $setup['tutor']->id,
        'curriculum_id' => $setup['curriculum_id'],
        'subject_id' => $setup['subject_id'],
        'weekday' => 2,
        'start_time' => '10:00:00',
        'timezone' => 'UTC',
        'starts_on' => '2026-09-14',
        'generated_until' => '2026-09-13',
        'price' => 10000,
    ]);

    Artisan::call('recurring:generate');

    return ['slot' => $slot->fresh(), 'parent' => $parent, 'learner' => $learner, 'setup' => $setup];
}

