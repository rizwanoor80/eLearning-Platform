<?php

namespace App\Filament\Resources\PayoutBatches\Tables;

use App\Enums\PayoutLineStatus;
use App\Models\PayoutBatch;
use App\Models\PayoutBatchLine;
use App\Services\Tutors\TutorEarnings;
use App\Support\Money;
use Filament\Actions\ViewAction;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Table;

class PayoutBatchesTable
{
    public static function configure(Table $table): Table
    {
        return $table
            ->modifyQueryUsing(fn ($query) => $query->with('createdBy')->withCount([
                'lines',
                'lines as pending_lines_count' => fn ($q) => $q->where('status', PayoutLineStatus::Pending->value),
                'lines as paid_lines_count' => fn ($q) => $q->where('status', PayoutLineStatus::Paid->value),
                'lines as failed_lines_count' => fn ($q) => $q->where('status', PayoutLineStatus::Failed->value),
            ])->withSum('lines', 'amount'))
            ->columns([
                TextColumn::make('id')->label('#')->sortable(),
                TextColumn::make('period_end')->label('Period end')->date()->sortable(),
                TextColumn::make('createdBy.name')->label('Generated by'),
                TextColumn::make('lines_count')->label('Tutors'),
                TextColumn::make('lines_sum_amount')
                    ->label('Total')
                    ->state(fn (PayoutBatch $record): string => Money::fils((int) $record->lines_sum_amount)->format()),
                TextColumn::make('progress')
                    ->label('Lines')
                    ->state(fn (PayoutBatch $record): string => "{$record->pending_lines_count} processing · {$record->paid_lines_count} paid · {$record->failed_lines_count} failed"),
                TextColumn::make('negative_balances')
                    ->label('Flags')
                    ->state(function (PayoutBatch $record): string {
                        $earnings = app(TutorEarnings::class);
                        $count = $record->lines()->with('tutorProfile')->get()
                            ->filter(fn (PayoutBatchLine $line): bool => $earnings->isOverpaid($line->tutorProfile))
                            ->count();

                        return $count === 0 ? '—' : "{$count} tutor(s) with a negative balance";
                    })
                    ->color(fn (string $state): string => $state === '—' ? 'gray' : 'danger'),
                TextColumn::make('created_at')->label('Generated')->dateTime()->sortable(),
            ])
            ->defaultSort('id', 'desc')
            ->recordActions([
                ViewAction::make(),
            ]);
    }
}
